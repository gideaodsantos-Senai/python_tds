print("Exércicio 1 - Calculo de 2 números inteiros")

num1 = int(input("Insira o número 1: "))
num2 = int(input("Insira o número 2: "))

soma = num1 + num2
produto = num1 * num2

print(f"A soma dos dois valores são {soma}\n O produto dos dois valores é {produto}")



print("Exércicio 2 - Conversão de metros em centímetros")

